/**
 * Copies the prototype's data file (server/db.json) into PostgreSQL:
 *   npm run db:import -- ../../reference/server/db.json
 * Passwords are hashed on the way in. Existing rows with the same id are replaced,
 * so it can be run again after a fix.
 */
import * as fs from 'fs';
import * as path from 'path';
import { PrismaClient } from '@prisma/client';
import * as bcrypt from 'bcryptjs';

try { process.loadEnvFile(path.resolve(__dirname, '../.env')); } catch { /* use the environment */ }

const prisma = new PrismaClient();

async function main() {
  const file = process.argv[2];
  if (!file) throw new Error('Give the path to db.json, e.g.  npm run db:import -- ../reference/server/db.json');
  const db = JSON.parse(fs.readFileSync(path.resolve(file), 'utf8'));
  const hash = (p: string) => bcrypt.hash(String(p || Math.random()), 10);

  for (const e of db.employees || []) {
    const data = {
      name: e.name, phone: e.phone || null, email: e.email || null, pin: String(e.pin), passwordHash: await hash(e.password),
      roles: e.roles?.length ? e.roles : ['field'], departmentId: e.departmentId || null, supervisorId: e.supervisorId || null,
      designation: e.designation || null, department: e.department || null, title: e.title || null,
      createdAt: e.createdAt ? new Date(e.createdAt) : new Date(),
    };
    await prisma.employee.upsert({ where: { id: e.id }, create: { id: e.id, ...data }, update: data });
  }
  console.log(`employees: ${(db.employees || []).length}`);

  for (const a of db.adminUsers || []) {
    const data = { name: a.name, email: a.email || null, pin: String(a.pin), passwordHash: await hash(a.password) };
    await prisma.adminUser.upsert({ where: { id: a.id }, create: { id: a.id, ...data }, update: data });
  }
  console.log(`admins: ${(db.adminUsers || []).length}`);

  for (const [i, d] of (db.departments || []).entries()) {
    await prisma.department.upsert({ where: { id: d.id }, create: { id: d.id, name: d.name, sortOrder: i }, update: { name: d.name, sortOrder: i } });
    for (const [j, u] of (d.units || []).entries()) {
      const data = { name: u.name, sortOrder: j, departmentId: d.id };
      await prisma.unit.upsert({ where: { id: u.id }, create: { id: u.id, ...data }, update: data });
    }
  }
  console.log(`units: ${(db.departments || []).length}`);

  for (const [i, o] of (db.offices || []).entries()) {
    const data = {
      name: o.name, type: o.type || 'branch', division: o.division || null, district: o.district || null, area: o.area || null,
      lat: o.lat ?? null, lng: o.lng ?? null, active: o.active !== false, sortOrder: i,
    };
    await prisma.office.upsert({ where: { id: o.id }, create: { id: o.id, ...data }, update: data });
  }
  console.log(`offices: ${(db.offices || []).length}`);

  for (const v of db.visits || []) {
    const fields = { employeeId: String(v.employeeId || ''), status: v.status === 'done' ? 'done' : 'open', date: v.date || null, data: v };
    await prisma.visit.upsert({ where: { id: v.id }, create: { id: v.id, ...fields }, update: fields });
  }
  console.log(`visits: ${(db.visits || []).length}`);

  for (const m of db.emailLog || []) {
    const data = {
      complaintId: m.complaintId || null, to: m.to || '', toName: m.toName || null, type: m.type || 'other',
      subject: m.subject || '', body: m.body || '', status: 'not-sent', error: 'Generated by the prototype (never sent).',
      sentAt: m.sentAt ? new Date(m.sentAt) : new Date(),
    };
    await prisma.emailLog.upsert({ where: { id: m.id }, create: { id: m.id, ...data }, update: data });
  }
  console.log(`emails: ${(db.emailLog || []).length}`);

  if (db.settings) {
    const { smtp, ...value } = db.settings;
    await prisma.setting.upsert({ where: { key: 'app' }, create: { key: 'app', value }, update: { value } });
    console.log('settings: done');
  }
}

main().finally(() => prisma.$disconnect());
